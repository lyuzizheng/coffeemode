#!/usr/bin/env node
/**
 * Generate `lib/api/rate-limit-buckets.generated.ts` from
 * `config/rate-limits.yaml` (BRAWUKA-625).
 *
 * The YAML is the single source of truth for bucket names. Adding a bucket
 * is one edit (the YAML) plus re-running this script:
 *
 *   npm run gen:buckets
 *
 * Zero-dependency on purpose: bucket names are the top-level mapping keys,
 * so a line scan suffices and the script runs on a fresh checkout before
 * `npm ci`. Freshness is enforced by `npm run check:guards`, which runs this
 * script's `--check` mode — a byte-for-byte comparison of the re-rendered
 * module against the committed file — in `application-static-gate` (the
 * deleted `tests/api/guard.test.ts` used to carry this; BRAWUKA-682).
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const YAML_FILE = join(root, "config", "rate-limits.yaml");
const OUT_FILE = join(root, "lib", "api", "rate-limit-buckets.generated.ts");

/**
 * Top-level keys of rate-limits.yaml, in file order: lines starting at
 * column 0 as `name:` (comments and indented window keys ignored).
 * Throws on empty input or duplicate keys.
 */
export function bucketNamesFromYamlText(text) {
  const names = [];
  const seen = new Set();
  for (const line of text.split("\n")) {
    if (line.startsWith("#") || line.trim() === "") continue;
    const match = /^([A-Za-z0-9][A-Za-z0-9_-]*):(\s|$)/.exec(line);
    if (!match) continue; // indented window key (`windowMs:`) or list item
    if (seen.has(match[1])) {
      throw new Error(`config rate-limits.yaml: duplicate bucket "${match[1]}"`);
    }
    seen.add(match[1]);
    names.push(match[1]);
  }
  if (names.length === 0) {
    throw new Error("config rate-limits.yaml: no buckets declared");
  }
  return names;
}

/** Render the generated module for the given bucket names (file order kept). */
export function renderBucketModule(names) {
  const entries = names.map((name) => `  "${name}",`).join("\n");
  return `// Code generated by \`scripts/generate-rate-limit-buckets.mjs\` from
// \`config/rate-limits.yaml\` (BRAWUKA-625). DO NOT EDIT — add the bucket to
// the YAML and run \`npm run gen:buckets\`.
export const RATE_LIMIT_BUCKET_NAMES = [
${entries}
] as const;

export type RateLimitBucketName = (typeof RATE_LIMIT_BUCKET_NAMES)[number];
`;
}

const isDirectRun = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];

if (isDirectRun) {
  const text = readFileSync(YAML_FILE, "utf8");
  const expected = renderBucketModule(bucketNamesFromYamlText(text));
  if (process.argv.includes("--check")) {
    const actual = readFileSync(OUT_FILE, "utf8");
    if (actual !== expected) {
      console.error(
        "❌ rate-limit-buckets.generated.ts is stale: re-run `npm run gen:buckets` after editing config/rate-limits.yaml.",
      );
      process.exit(1);
    }
    console.log("✅ rate-limit-buckets.generated.ts matches config/rate-limits.yaml.");
  } else {
    writeFileSync(OUT_FILE, expected);
    console.log(`✅ Wrote ${OUT_FILE} (${bucketNamesFromYamlText(text).length} buckets).`);
  }
}
